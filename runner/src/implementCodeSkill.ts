// The /implement-code skill's text: the implement step's shared body (implementStep.ts) with an interactive opening and
// ending in place of the step's record-returning one. The committed skill is runner/skills/implement-code/SKILL.md;
// byro-repo's drift test regenerates it from byro-repo's commands.

import { implementBody } from "./implementStep.ts";
import { stepReadLine } from "./IssueReader.ts";
import { sectionOf } from "./promptText.ts";
import { resolveRecordFields } from "./resolveStep.ts";

export interface ImplementCodeSkillInput {
  // Each command is written with `<repo>` and `<n>` placeholders; the promote command takes the repo to promote last.
  promoteCommand: string;
  reviewCommand: string;
  // Takes the records file's path last.
  resolveCommand: string;
  wrapUpCommand: string;
}

export function implementCodeSkillOf(input: ImplementCodeSkillInput): string {
  return `${[
    frontmatter,
    "`/implement-code <repo>#<n>` implements one ticket in an interactive session, from the same body as the spec runner's implement step; only the ending differs.",
    openingSection(input),
    workingSection(),
    gitHubSection(),
    endingSection(input),
  ].join("\n\n")}\n`;
}

const frontmatter = `---
name: implement-code
description: "Implement one code ticket in its issue workspace, review it with the spec runner, report, and land it with wrap-up once the developer says go. Invoked as /implement-code <repo>#<n>."
disable-model-invocation: true
---

<!-- Generated by runner/src/implementCodeSkill.ts; edit that, then run \`npx vitest run scripts/runner/implementCodeSkill.test.ts -u\`. -->`;

function openingSection({ promoteCommand }: ImplementCodeSkillInput): string {
  return sectionOf("Before you start", [
    "Read the ticket and state its title before starting. If the reference is ambiguous, ask.",
    "A `ready-for-human` ticket: state its title, name the skill or steps its body says to run, and stop.",
    "Work only in the ticket's issue workspace. When your working directory is a primary checkout, stop and tell the developer to move this session into the workspace first.",
    `The repos the workspace put on the ticket's \`issue-<n>-*\` branch take edits; every other repo is detached at master. To change one, first run \`${promoteCommand} <repo-to-promote>\`. Never switch, create or delete a branch yourself.`,
  ]);
}

function workingSection(): string {
  return sectionOf("How you work", [
    implementBody.testFirst,
    implementBody.checking,
    implementBody.oneCommand,
  ]);
}

function gitHubSection(): string {
  return sectionOf("GitHub", [implementBody.gitHubWrites, stepReadLine]);
}

function endingSection({
  reviewCommand,
  resolveCommand,
  wrapUpCommand,
}: ImplementCodeSkillInput): string {
  return `## When you're done

- ${implementBody.drift}
- ${implementBody.committing} When it fails only on something your change didn't cause, carry on and name the failure in your report.
- ${implementBody.onlyWrites}. The review and wrap-up commands in the ending make every other write.
- Run git commands one at a time: inside an entered worktree, Claude Code refuses a compound git command.
- Then, in order:
  1. **Review**: run \`${reviewCommand}\`, resolving \`<repo>\` to \`<owner>/<repo>\` here and in resolve. It runs the runner's review session on this ticket and records it. While this session's context is under the ticket budget, it prints the findings, numbered, each with its axis and suggested verdict, for you to resolve; past it, a fresh resolver resolves them instead and it goes straight to the review list.
  2. **Resolve**, when it printed findings: ${implementBody.resolving} Then run \`npm run check\`. Write \`.runner/resolve-<n>.json\`, gitignored, as \`{ "records": [...] }\`, ${indentedOf(resolveRecordFields)}

     Then run \`${resolveCommand} .runner/resolve-<n>.json\`. It checks the records and your commits by the run's rules; when it refuses them, correct what it names and run it again.
  3. Either way, review or resolve prints the review list, by axis then verdict with each suggested verdict overruled, and writes the review facts. It prints each Halt as \`S<n>.<k>\`; answer it with the developer in the session. When it exits short of reviewed, report why and stop.
  4. **Report**: post in the session what review caught and what was fixed, then each Propose on its own line, the item then \`→\` and its record's \`recommendation\`.
  5. **Wait for the developer's go-ahead.** Land nothing before it.
  6. Call \`ExitWorktree\` with \`keep\`, so wrap-up can remove the workspace.
  7. **Land**: \`${wrapUpCommand} --closing "<what landed>" [--undone "<box>: <reason>"]...\`, one \`--undone\` per acceptance box left undone. A ticket with no branch ahead of master, one that needed only GitHub or Doc writes, adds \`--no-code\`: \`${wrapUpCommand} --no-code --closing "<what landed>"\`. A ticket that changes wrap-up or the facts file's format lands through its workspace's own script instead, by \`docs/agents/git-workflow.md\`.`;
}

// Under a numbered step's text, so a list inside it stays in the step.
function indentedOf(text: string): string {
  return text.replaceAll(/\n(?=.)/g, "\n     ");
}
