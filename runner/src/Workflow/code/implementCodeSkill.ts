// The /implement-code skill's text: the implement step's shared body (stepPrompts.ts) with an interactive opening and
// the generated skills' shared ending in place of the step's record-returning one. The committed skill is
// runner/skills/implement-code/SKILL.md; byro-repo's drift test regenerates it from byro-repo's commands.

import { stepReadLine } from "../../IssueReader.ts";
import { sectionOf } from "../../promptText.ts";
import {
  implementBody,
  type InteractiveSkillInput,
  interactiveSkillOf,
  ticketBindsSection,
} from "../../stepPrompts.ts";

export interface ImplementCodeSkillInput extends Omit<
  InteractiveSkillInput,
  "body" | "checkCommand"
> {
  // Written with `<repo>` and `<n>` placeholders; takes the repo to promote last.
  promoteCommand: string;
}

export function implementCodeSkillOf({
  promoteCommand,
  ...ending
}: ImplementCodeSkillInput): string {
  return interactiveSkillOf({
    ...ending,
    body: [
      frontmatter,
      "`/implement-code <repo> <n>` implements one ticket in an interactive session, from the same body as the spec runner's implement step; only the ending differs.",
      openingSection(promoteCommand),
      workingSection(),
      ticketBindsSection(),
      gitHubSection(),
    ].join("\n\n"),
    checkCommand: "npm run check",
  });
}

const frontmatter = `---
name: implement-code
description: "Implement one code ticket in its issue workspace, review it with the spec runner, report, and land it with wrap-up once the developer says go. Invoked as /implement-code <repo> <n>."
disable-model-invocation: true
---

<!-- Generated by runner/src/Workflow/code/implementCodeSkill.ts; edit that, then run \`npx vitest run scripts/runner/implementCodeSkill.test.ts -u\`. -->`;

function openingSection(promoteCommand: string): string {
  return sectionOf("Before you start", [
    "Read the ticket and state its title before starting. If the reference is ambiguous, ask.",
    "A `ready-for-human` ticket: state its title, name the skill or steps its body says to run, and stop.",
    "A `ready-for-interactive` ticket is an Interactive ticket: implement it here, since its work needs the developer's yes, which this session can ask for.",
    "Work only in the ticket's issue workspace. When your working directory is a primary checkout, stop and tell the developer to move this session into the workspace first.",
    `The repos the workspace put on the ticket's \`issue-<n>-*\` branch take edits; every other repo is detached at master. To change one, first run \`${promoteCommand} <repo-to-promote>\`. Never switch, create or delete a branch yourself.`,
  ]);
}

function workingSection(): string {
  return sectionOf("How you work", [
    implementBody.testFirst,
    implementBody.checking,
    implementBody.oneCommand,
  ]);
}

function gitHubSection(): string {
  return sectionOf("GitHub", [implementBody.gitHubWrites, stepReadLine]);
}
